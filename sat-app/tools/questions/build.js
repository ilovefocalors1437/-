'use strict';
/* Runs every template generator and writes www/data/questions.js deterministically.
   Usage: node build.js            */
const fs = require('fs');
const path = require('path');
const L = require('./lib');

const SOURCES = ['./gen-algebra', './gen-advanced', './gen-psda', './gen-geometry', './hand'];
const OUT = path.join(__dirname, '../../www/data/questions.js');

function loadTemplates() {
  const all = [];
  for (const s of SOURCES) for (const t of require(s)) all.push(t);
  return all;
}

function genOne(t, v) {
  for (let att = 0; att < 400; att++) {
    const r = L.makeRng((L.hashStr(t.tpl) + v * 7919 + att * 104729) >>> 0);
    let out;
    try { out = t.gen(r, v); } catch (e) { if (e instanceof L.Reject) continue; e.message = `[${t.tpl} v${v}] ` + e.message; throw e; }
    out._att = att;
    return out;
  }
  throw new Error(`[${t.tpl} v${v}] could not satisfy preconditions`);
}

function build() {
  const templates = loadTemplates();
  const tplSeen = new Set();
  const items = [];
  let verified = 0, unverified = [];
  for (const t of templates) {
    if (tplSeen.has(t.tpl)) throw new Error('duplicate tpl ' + t.tpl);
    tplSeen.add(t.tpl);
    const stems = new Set();
    for (let v = 0; v < (t.n || 1); v++) {
      let out, tries = 0;
      // ensure variants of a template differ
      for (;;) {
        out = genOne(t, v + tries * 101);
        if (!stems.has(out.stem)) break;
        if (++tries > 30) throw new Error('cannot make distinct variant for ' + t.tpl);
      }
      stems.add(out.stem);
      if (out.verify) {
        let ok;
        try { ok = out.verify(); } catch (e) { e.message = `[${t.tpl} v${v}] verify threw: ` + e.message; throw e; }
        if (ok !== true) throw new Error(`[${t.tpl} v${v}] verify failed`);
        verified++;
      } else unverified.push(t.tpl);
      const q = {
        id: `${t.tpl}-v${v + 1}`,
        tpl: t.tpl, domain: t.domain, skill: t.skill, difficulty: t.diff, type: t.type,
        stem: out.stem,
      };
      if (t.type === 'mcq') {
        L.assert(Array.isArray(out.choices) && out.choices.length === 4, t.tpl + ' needs 4 choices');
        L.assert(L.distinct(out.choices), t.tpl + ' choices not distinct: ' + out.choices.join(' | '));
        q._choices = out.choices; q._order = out.order || null;
      } else {
        L.assert(Array.isArray(out.answer) && out.answer.length, t.tpl + ' spr answer');
        q.answer = out.answer;
      }
      q.explanation = out.explanation;
      items.push(q);
    }
  }
  placeChoices(items);
  return { items, verified, unverified };
}

// Put the correct choice (index 0 from the generator) in a balanced position.
function placeChoices(items) {
  const mcq = items.filter((q) => q.type === 'mcq');
  const counts = [0, 0, 0, 0];
  const free = [];
  for (const q of mcq) {
    if (q._order) {
      const idx = q._choices.map((c, i) => i).sort((a, b) => q._order[a] - q._order[b]);
      q.choices = idx.map((i) => q._choices[i]);
      q.answer = idx.indexOf(0);
      counts[q.answer]++;
    } else free.push(q);
  }
  const total = mcq.length;
  const r = L.makeRng(20240601);
  // positions to hand out so that the overall distribution is as even as possible
  const slots = [];
  const target = [0, 1, 2, 3].map(() => total / 4);
  const left = free.length;
  const deficit = target.map((t, i) => Math.max(0, t - counts[i]));
  const dsum = deficit.reduce((a, b) => a + b, 0);
  let alloc = deficit.map((d) => Math.floor(d / dsum * left));
  let rem = left - alloc.reduce((a, b) => a + b, 0);
  for (let i = 0; rem > 0; i = (i + 1) % 4) { alloc[i]++; rem--; }
  alloc.forEach((a, i) => { for (let k = 0; k < a; k++) slots.push(i); });
  const order = r.shuffle(slots);
  free.forEach((q, k) => {
    const pos = order[k];
    const others = r.shuffle(q._choices.slice(1));
    others.splice(pos, 0, q._choices[0]);
    q.choices = others; q.answer = pos;
  });
  for (const q of mcq) {
    delete q._choices; delete q._order;
    // reorder keys for readability
    const { explanation } = q; delete q.explanation; q.explanation = explanation;
  }
  // move answer after choices for mcq
  for (const q of mcq) { const a = q.answer, e = q.explanation; delete q.answer; delete q.explanation; q.answer = a; q.explanation = e; }
}

if (require.main === module) {
  const { items, verified, unverified } = build();
  const header = '/* Generated by tools/questions/build.js — do not edit by hand. */\n' +
    "var window = typeof window !== 'undefined' ? window : globalThis;\n";
  const body = 'window.SAT_QUESTIONS = ' + JSON.stringify(items, null, 1) + ';\n' +
    "if (typeof module !== 'undefined' && module.exports) module.exports = window.SAT_QUESTIONS;\n";
  fs.writeFileSync(OUT, header + body);
  const by = {};
  for (const q of items) { const k = q.domain; by[k] = (by[k] || 0) + 1; }
  console.log(`wrote ${items.length} questions (${new Set(items.map((q) => q.tpl)).size} templates) to ${OUT}`);
  console.log('by domain', by, '| verified variants', verified, '| without verify', unverified.length, [...new Set(unverified)].length + ' tpls');
}
module.exports = { build };
